async def test_sample_spec_is_repeatable(
    c: OracleConnector, oracle_conn: Any, oracle_schema: OracleTestSchema
) -> None:
    create_customers(oracle_conn, oracle_schema.owner, 200)
    shape = await c.describe(_obj(oracle_schema, "CUSTOMERS"))
    sel = Selection(sample=SampleSpec(percent=40, seed=7))
    first = _keys(await _read(c, shape, sel, batch=13), shape)
    assert first == _keys(await _read(c, shape, sel, batch=13), shape)
    assert 0 < len(first) < 200
    assert await c.count(shape, sel, {}) == len(first)
    cut = encode_key((FIRST + 100,), shape.key_columns())  # partitions split the same sample
    left = _keys(await _read(c, shape, sel, KeyRange(upper=cut), batch=9), shape)
    right = _keys(await _read(c, shape, sel, KeyRange(lower=cut), batch=9), shape)
    assert left + right == first
    other = _keys(await _read(c, shape, Selection(sample=SampleSpec(percent=40, seed=8))), shape)
    assert other != first
    query = Selection(  # a query is sampled by the same key hash
        query=f'SELECT CUSTOMER_ID, SEGMENT FROM "{oracle_schema.owner}"."CUSTOMERS"',
        sample=SampleSpec(percent=40, seed=7),
    )
    assert _keys(await _read(c, shape, query, batch=17), shape) == first
    assert await c.count(shape, query, {}) == len(first)
    narrowed = Selection(where="SEGMENT = 'premium'", sample=SampleSpec(percent=40, seed=7))
    premium = {FIRST + i for i in range(200) if i % 3 == 0}
    assert _keys(await _read(c, shape, narrowed), shape) == [k for k in first if k[0] in premium]


async def test_reads_never_lock_rows(
    c: OracleConnector, oracle_conn: Any, oracle_schema: OracleTestSchema
) -> None:
    o = oracle_schema.owner
    create_customers(oracle_conn, o, 20)
    shape = await c.describe(_obj(oracle_schema, "CUSTOMERS"))
    pages = c.read_partition(shape, Selection(), {}, KeyRange(), after_key=None, batch=5)
    first = await anext(pages)  # the generator is suspended between pages

    def update() -> None:
        with oracledb.connect(
            user=o, password=oracle_schema.owner_password, dsn=oracle_schema.dsn
        ) as other:
            other.call_timeout = 2000
            with other.cursor() as cur:
                cur.execute(
                    f'UPDATE "{o}"."CUSTOMERS" SET SEGMENT = \'x\' WHERE CUSTOMER_ID = :k',
                    {"k": first[0]["CUSTOMER_ID"]},
                )
                assert cur.rowcount == 1
            other.commit()

    await asyncio.to_thread(update)  # no DPY-4024: no page holds a lock or a cursor
    rest = [r for page in [p async for p in pages] for r in page]
    assert len(first) + len(rest) == 20


