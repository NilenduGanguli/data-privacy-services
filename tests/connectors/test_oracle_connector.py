async def test_describe_unique_fallback_and_identity(
    c: OracleConnector, oracle_conn: Any, oracle_schema: OracleTestSchema
) -> None:
    o = oracle_schema.owner
    with oracle_conn.cursor() as cur:
        cur.execute(
            f'CREATE TABLE "{o}"."U" (A NUMBER NOT NULL, B VARCHAR2(8), CONSTRAINT U_UQ UNIQUE (A))'
        )
        cur.execute(
            f'CREATE TABLE "{o}"."I" (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
            "X VARCHAR2(4))"
        )
        # a unique constraint on a nullable column is not a key; a unique NOT NULL index is
        cur.execute(
            f'CREATE TABLE "{o}"."UN" (A NUMBER, B VARCHAR2(8) NOT NULL, CONSTRAINT UN_UQ UNIQUE (A))'
        )
        cur.execute(f'CREATE UNIQUE INDEX "{o}"."UN_B" ON "{o}"."UN" (B)')
    u = await c.describe(_obj(oracle_schema, "U"))
    assert u.key == ["A"] and u.key_source == "unique_index"
    ident = await c.describe(_obj(oracle_schema, "I"))
    assert ident.column("ID").is_identity is True and ident.key == ["ID"]
    un = await c.describe(_obj(oracle_schema, "UN"))
    assert un.key == ["B"] and un.key_source == "unique_index"


async def test_describe_keyless_table_uses_rowid(
    c: OracleConnector, oracle_conn: Any, oracle_schema: OracleTestSchema
) -> None:
    o = oracle_schema.owner
    with oracle_conn.cursor() as cur:
        cur.execute(f'CREATE TABLE "{o}"."H" (A NUMBER, B VARCHAR2(8))')
        cur.executemany(f'INSERT INTO "{o}"."H" VALUES (:1, :2)', [(i, f"b{i}") for i in range(90)])
    oracle_conn.commit()
    shape = await c.describe(_obj(oracle_schema, "H"))
    assert shape.key == ["ROWID"] and shape.key_source == "rowid"
    last = shape.columns[-1]
    assert last.pseudo and last.is_key and last.name == "ROWID"
    # ROWID ranges cut at sampled quantiles cover every row exactly once
    keys = await c.sample_keys(shape, Selection(), {}, 20)
    assert keys and all(isinstance(k[0], int) for k in keys)
    seen: list[int] = []
    for rng in ranges_from_keys(keys, 4, shape.key_columns()):
        pages = await _read(c, shape, key_range=rng, batch=7)
        seen += [r["A"] for page in pages for r in page]
    assert sorted(seen) == list(range(90))
    with pytest.raises(SelectionError) as err:  # a query cannot page a key-less table
        await c.count(shape, Selection(query=f'SELECT A FROM "{o}"."H"'), {})
    assert err.value.code == "selection_query_needs_key"


