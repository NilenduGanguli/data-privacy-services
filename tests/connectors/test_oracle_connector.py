async def test_count_where_binds_and_max_rows(
    c: OracleConnector, oracle_conn: Any, oracle_schema: OracleTestSchema
) -> None:
    create_customers(oracle_conn, oracle_schema.owner, 30)
    shape = await c.describe(_obj(oracle_schema, "CUSTOMERS"))
    premium = Selection(where="SEGMENT = :seg", params={"seg": "premium"})
    assert await c.count(shape, premium, premium.params) == 10
    capped = premium.model_copy(update={"max_rows": 4})
    assert await c.count(shape, capped, capped.params) == 4
    literal = Selection(where="SEGMENT = 'premium' AND CUSTOMER_ID >= 10000010")
    assert await c.count(shape, literal, {}) == 7  # literals are bound, never interpolated
    with pytest.raises(SelectionError) as err:
        await c.count(shape, Selection(where="SEGMENT = :seg"), {})
    assert err.value.code == "selection_param_missing"
    with pytest.raises(SelectionError) as err:
        await c.count(shape, premium, {})  # the run's params lack the bind
    assert err.value.code == "selection_param_missing"
    with pytest.raises(SelectionError):
        await c.count(shape, Selection(where="SEGMENT = 'x'; DELETE FROM CUSTOMERS"), {})


