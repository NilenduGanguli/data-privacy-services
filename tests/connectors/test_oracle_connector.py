async def test_connection_test_as_read_only_user(
    c: OracleConnector, oracle_admin: Any, oracle_conn: Any, oracle_schema: OracleTestSchema
) -> None:
    create_customers(oracle_conn, oracle_schema.owner, 3)
    oracle_schema.grant_select(oracle_admin, "CUSTOMERS")
    obj = _obj(oracle_schema, "CUSTOMERS")
    ro = _connector(oracle_schema, user=oracle_schema.ro_user, password=oracle_schema.ro_password)
    try:
        source = await ro.test(role="source", obj=obj)
        assert source.ok and source.engine == "oracle" and source.server_version
        checks = {ch["name"]: ch for ch in source.checks}
        assert checks["connect"]["ok"] and checks["select_source"]["ok"]
        assert checks["no_dml_on_source"]["ok"] and checks["no_dml_on_source"]["severity"] == (
            "advisory"
        )
        assert source.capabilities["rowid"] and not source.capabilities["copy"]
        target = await ro.test(role="target", obj=obj, write_mode="in_place")
        assert target.ok is False
        by = {ch["name"]: ch for ch in target.checks}
        assert by["update_target"]["ok"] is False and by["create_ledger"]["ok"] is False
        for result in (source, target):
            text = result.model_dump_json()
            assert oracle_schema.ro_password not in text and oracle_schema.dsn not in text
    finally:
        await ro.close()
    owner = await c.test(role="target", obj=obj, write_mode="in_place")
    assert owner.ok, owner.checks
    missing = await c.test(role="target", obj=_obj(oracle_schema, "NEW_T"), write_mode="table")
    assert missing.ok and {ch["name"] for ch in missing.checks} >= {"create_target"}


async def test_bad_password_is_connection_failed(oracle_schema: OracleTestSchema) -> None:
    sentinel = "Wrong-Sentinel-9431"
    bad = _connector(oracle_schema, password=sentinel)
    try:
        with pytest.raises(ConnectorError) as err:
            await bad.open()
        assert err.value.code == "connection_failed" and err.value.detail == "ORA-01017"
        assert not err.value.retryable and sentinel not in str(err.value)
        result = await bad.test(role="source")
        assert result.ok is False and result.error_code == "connection_failed"
        assert sentinel not in result.model_dump_json()
    finally:
        await bad.close()
