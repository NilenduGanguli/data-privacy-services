def _obj(schema: OracleTestSchema, name: str) -> ObjectRef:
    return ObjectRef(owner=schema.owner, name=name)


async def _read(
    c: OracleConnector,
    shape: TableShape,
    selection: Selection | None = None,
    key_range: KeyRange | None = None,
    *,
    after: tuple[Any, ...] | None = None,
    batch: int = 50,
) -> list[list[Row]]:
    sel = selection or Selection()
    return [
        page
        async for page in c.read_partition(
            shape, sel, dict(sel.params), key_range or KeyRange(), after_key=after, batch=batch
        )
    ]


def _keys(pages: list[list[Row]], shape: TableShape) -> list[tuple[Any, ...]]:
    return [key_tuple(r, shape) for page in pages for r in page]


